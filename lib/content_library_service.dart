// ContentLibraryService — unified, read-only source of truth for every idea in the app.
//
// Before this file, ideas lived in three disconnected places:
//   * HookStore (hooks.json) — user-edited built-in HookIdeas
//   * kDefaultHooks / kDefaultHooksWithRewrite — the const built-in list in memory
//   * QuickIdeaStore (quick_ideas.json) — user-created QuickIdeas from the old inbox
//   * kDefaultHooks — built-in ideas, including the former 14-day post packages
//
// The Content Library screen only knew about ContentLibraryItem (the generated-package
// store), not the idea sources above it. The Idea Vault screen only knew about
// IdeaInboxItem. A user could not review a built-in HookIdea and an inbox idea in the
// same list, could not search across both, and could not pick a built-in idea to
// "Create Content" from.
//
// ContentLibraryService fixes that by presenting one normalized `ContentIdea` view
// over every source. It does **not** delete any storage — HookStore, QuickIdeaStore,
// and the const lists remain intact. It reads from all of them and merges results,
// deduplicating by stable ID and preserving user edits.

