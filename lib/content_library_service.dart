/// A single normalized idea that unifies HookIdea and QuickIdea.
///
/// The Content Library needs one shape to display everything: built-in hooks,
/// user-edited hooks, safety hooks, day-14 carousel ideas, and user-added ideas.
/// This class is the union of those two source models, exposing only the fields
/// that every screen needs to show a card, run a review, or start generation.
class ContentIdea {
  /// Stable, unique ID. For built-in ideas this is the `id` on HookIdea / QuickIdea;
  /// for user-added ideas it is generated by [ContentLibraryService.addIdea].
  final String id;

  /// Display title / cover line.
  final String title;

  /// The category this idea belongs to (e.g. "Relatable", "Safety", "Food").
  ///
  /// This is the HookIdea `category` or, for QuickIdeas, derived from the bucket
  /// via the bucket-to-category mapping in [bucketToCategory].
  final String category;

  /// Collection id from `content_collections.dart`, e.g. "routines", "robot".
  final String collectionId;

  /// "Reel", "Carousel", "Static Image", "Trial Reel".
  final String format;

  /// The core problem or concept of the idea.
  final String problem;

  /// The learning outcome or lesson.
  final String lesson;

  /// The opening hook / first line.
  final String opening;

  /// The full story detail, if available (Story/Twist/Resolution/Moral format).
  final String storyDetail;

  /// Characters mentioned in the idea, as character IDs.
  final List<String> characterIds;

  /// Hashtag or caption, if the idea carries one.
  final String caption;

  /// Whether this idea was added by the user (vs. built-in).
  final bool isCustom;

  /// Production status: where this idea sits in the workflow.
  final IdeaStatus status;

  /// Any notes attached to the idea.
  final String notes;

  /// Reference back to the original HookIdea or QuickIdea for full-detail screens.
  /// Set to the runtime type name: "HookIdea" or "QuickIdea".
  final String sourceType;

  /// The raw source ID for traceability — same as [id] for built-ins and
  /// custom ideas that originated from the inbox.
  final String? sourceIdeaId;

  const ContentIdea({
    required this.id,
    required this.title,
    required this.category,
    required this.collectionId,
    required this.format,
    required this.problem,
    required this.lesson,
    required this.opening,
    required this.storyDetail,
    required this.characterIds,
    required this.caption,
    required this.isCustom,
    required this.status,
    required this.notes,
    required this.sourceType,
    this.sourceIdeaId,
  });

  ContentIdea copyWith({
    String? title,
    String? category,
    String? collectionId,
    String? format,
    String? problem,
    String? lesson,
    String? opening,
    String? storyDetail,
    List<String>? characterIds,
    String? caption,
    bool? isCustom,
    IdeaStatus? status,
    String? notes,
  }) {
    return ContentIdea(
      id: id,
      title: title ?? this.title,
      category: category ?? this.category,
      collectionId: collectionId ?? this.collectionId,
      format: format ?? this.format,
      problem: problem ?? this.problem,
      lesson: lesson ?? this.lesson,
      opening: opening ?? this.opening,
      storyDetail: storyDetail ?? this.storyDetail,
      characterIds: characterIds ?? this.characterIds,
      caption: caption ?? this.caption,
      isCustom: isCustom ?? this.isCustom,
      status: status ?? this.status,
      notes: notes ?? this.notes,
      sourceType: sourceType,
      sourceIdeaId: sourceIdeaId,
    );
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'title': title,
    'category': category,
    'collectionId': collectionId,
    'format': format,
    'problem': problem,
    'lesson': lesson,
    'opening': opening,
    'storyDetail': storyDetail,
    'characterIds': characterIds,
    'caption': caption,
    'isCustom': isCustom,
    'status': status.name,
    'notes': notes,
    'sourceType': sourceType,
    'sourceIdeaId': sourceIdeaId,
  };

  factory ContentIdea.fromJson(Map<String, dynamic> json) => ContentIdea(
    id: json['id'] as String? ?? '',
    title: json['title'] as String? ?? '',
    category: json['category'] as String? ?? 'Relatable',
    collectionId:
        json['collectionId'] as String? ??
        collectionOf(
          json['id'] as String? ?? '',
          custom: json['isCustom'] as bool? ?? false,
        ),
    format: json['format'] as String? ?? 'Reel',
    problem: json['problem'] as String? ?? '',
    lesson: json['lesson'] as String? ?? '',
    opening: json['opening'] as String? ?? '',
    storyDetail: json['storyDetail'] as String? ?? '',
    characterIds: ((json['characterIds'] as List?) ?? const [])
        .map((e) => e as String)
        .toList(),
    caption: json['caption'] as String? ?? '',
    isCustom: json['isCustom'] as bool? ?? false,
    status: IdeaStatus.fromLegacy(json['status'] as String? ?? 'idea'),
    notes: json['notes'] as String? ?? '',
    sourceType: json['sourceType'] as String? ?? 'ContentIdea',
    sourceIdeaId: json['sourceIdeaId'] as String?,
  );
}

/// Maps a BucketLibrary id to a category label for QuickIdea display.
String bucketToCategory(String bucketId) {
  final bucket = BucketLibrary.byId(bucketId);
  if (bucket != null) return bucket.name;
  return 'General';
}

/// The unified service that reads from every idea source and presents
/// one merged, deduplicated list of [ContentIdea].
class ContentLibraryService {
  // ── Singleton ──────────────────────────────────────────────────────────

  ContentLibraryService._private();

  static final ContentLibraryService instance =
      ContentLibraryService._private();

  // ── Caching ───────────────────────────────────────────────────────────

  List<ContentIdea>? _cache;
  DateTime? _cacheTime;
  static const _cacheTtl = Duration(minutes: 1);

  /// Whether the cache should be considered stale.
  bool get _isCacheStale {
    if (_cache == null || _cacheTime == null) return true;
    return DateTime.now().difference(_cacheTime!) > _cacheTtl;
  }

  /// Clears the in-memory cache. Call after any write (add / update / delete)
  /// so that the next read reflects the change.
  void invalidateCache() {
    _cache = null;
    _cacheTime = null;
  }

  // ── Public read API ───────────────────────────────────────────────────

  /// Returns every unique idea from every source, merged and deduplicated.
  ///
  /// Order: built-ins first (sorted by category), then user-added ideas.
  /// Each idea appears exactly once even if it exists in multiple sources.
  Future<List<ContentIdea>> getAllIdeas() async {
    if (!_isCacheStale && _cache != null) return _cache!;

    final ideas = await _loadAll();
    _cache = ideas;
    _cacheTime = DateTime.now();
    return ideas;
  }

  /// Returns all ideas filtered to [categoryId].
  Future<List<ContentIdea>> getIdeasByCategory(String categoryId) async {
    final all = await getAllIdeas();
    return all.where((i) => i.category == categoryId).toList();
  }

  /// Returns all ideas filtered to [collectionId] (e.g. "routines", "robot").
  Future<List<ContentIdea>> getIdeasByCollection(String collectionId) async {
    final all = await getAllIdeas();
    return all.where((i) => i.collectionId == collectionId).toList();
  }

  /// Search across title, opening, problem, and lesson.
  Future<List<ContentIdea>> searchIdeas(String query) async {
    final q = query.toLowerCase();
    if (q.isEmpty) return getAllIdeas();
    final all = await getAllIdeas();
    return all
        .where(
          (i) =>
              i.title.toLowerCase().contains(q) ||
              i.opening.toLowerCase().contains(q) ||
              i.problem.toLowerCase().contains(q) ||
              i.lesson.toLowerCase().contains(q) ||
              i.storyDetail.toLowerCase().contains(q),
        )
        .toList();
  }

  /// Look up a single idea by its stable ID.
  Future<ContentIdea?> getIdeaById(String id) async {
    final all = await getAllIdeas();
    try {
      return all.firstWhere((i) => i.id == id);
    } catch (_) {
      return null;
    }
  }

  /// All distinct category labels across all ideas.
  Future<List<String>> getCategories() async {
    final all = await getAllIdeas();
    final cats = <String>{};
    for (final i in all) {
      if (i.category.isNotEmpty) cats.add(i.category);
    }
    return cats.toList()..sort();
  }

  /// All distinct collection ids that have at least one idea.
  Future<List<String>> getCollections() async {
    final all = await getAllIdeas();
    final colls = <String>{};
    for (final i in all) {
      colls.add(i.collectionId);
    }
    return colls.toList()..sort();
  }

  /// Ideas related to [ideaId] by collection or category.
  Future<List<ContentIdea>> getRelatedIdeas(String ideaId) async {
    final target = await getIdeaById(ideaId);
    if (target == null) return [];
    final all = await getAllIdeas();
    return all
        .where(
          (i) =>
              (i.collectionId == target.collectionId && i.id != ideaId) ||
              (i.category == target.category && i.id != ideaId),
        )
        .toList();
  }

  // ── Public write API ──────────────────────────────────────────────────

  /// Adds a new custom idea, persisting it to the inbox store so it
  /// survives restarts and appears in [getAllIdeas].
  ///
  /// Returns the newly created [ContentIdea]. The ID is generated
  /// deterministically from the title + timestamp to be stable yet unique.
  Future<ContentIdea> addIdea(ContentIdea idea) async {
    final id = idea.id.isNotEmpty
        ? idea.id
        : 'u${DateTime.now().millisecondsSinceEpoch}';

    final withId = ContentIdea(
      id: id,
      title: idea.title,
      category: idea.category,
      collectionId: idea.collectionId,
      format: idea.format,
      problem: idea.problem,
      lesson: idea.lesson,
      opening: idea.opening,
      storyDetail: idea.storyDetail,
      characterIds: idea.characterIds,
      caption: idea.caption,
      isCustom: true,
      status: IdeaStatus.idea,
      notes: idea.notes,
      sourceType: 'ContentIdea',
    );

    // Persist to the inbox store so it survives restarts.
    final inboxItem = IdeaInboxItem(
      id: id,
      title: withId.title,
      rawIdea: withId.problem.isNotEmpty ? withId.problem : withId.title,
      bucketId: _categoryToBucketId(withId.category),
      notes: withId.notes,
      status: IdeaStatus.idea,
      createdAt: DateTime.now(),
      updatedAt: DateTime.now(),
    );
    await IdeaInboxStore.add(inboxItem);
    invalidateCache();
    return withId;
  }

  /// Updates an existing idea (by ID) with the given fields.
  /// Only custom ideas can be updated — built-in ideas are preserved
  /// as-is to avoid losing the canonical source.
  Future<void> updateIdea(ContentIdea idea) async {
    if (!idea.isCustom) {
      // For built-in ideas, we rely on HookStore.save() for HookIdea edits.
      // That path is handled by the caller in HookStore directly.
      return;
    }
    // Find and update the corresponding inbox item.
    final inboxItems = await IdeaInboxStore.load();
    final updated = inboxItems.map((i) {
      if (i.id != idea.id) return i;
      return i.copyWith(
        title: idea.title,
        rawIdea: idea.problem.isNotEmpty ? idea.problem : idea.title,
        bucketId: _categoryToBucketId(idea.category),
        notes: idea.notes,
        status: idea.status,
        updatedAt: DateTime.now(),
      );
    }).toList();
    await IdeaInboxStore.save(updated);
    invalidateCache();
  }

  /// Deletes a custom idea by ID. Built-in ideas cannot be deleted.
  Future<void> deleteIdea(String id) async {
    await IdeaInboxStore.delete(id);
    invalidateCache();
  }

  // ── Internal: loading & merging ───────────────────────────────────────

  /// Reads all sources, normalizes to ContentIdea, deduplicates by ID.
  Future<List<ContentIdea>> _loadAll() async {
    final seen = <String>{};
    final result = <ContentIdea>[];

    // 1. Built-in hooks with rewrites applied
    for (final h in kDefaultHooksWithRewrite) {
      if (!seen.add(h.id)) continue;
      result.add(_hookToIdea(h, isCustom: h.custom));
    }

    // 2. Saved user-edited hooks from HookStore (these override built-ins)
    final savedHooks = await HookStore.load();
    for (final h in savedHooks) {
      if (!seen.add(h.id)) continue;
      result.add(_hookToIdea(h, isCustom: h.custom));
    }

    // 3. User-added QuickIdeas from the store
    final savedQuickIdeas = await QuickIdeaStore.load();
    for (final q in savedQuickIdeas) {
      if (!seen.add(q.id)) continue;
      result.add(_quickIdeaToContentIdea(q));
    }

    // 4. User-added ideas from the inbox
    final inboxItems = await IdeaInboxStore.load();
    for (final i in inboxItems) {
      if (!seen.add(i.id)) continue;
      result.add(_inboxToContentIdea(i));
    }

    return result;
  }

  /// Converts a HookIdea into a normalized ContentIdea.
  ContentIdea _hookToIdea(HookIdea h, {required bool isCustom}) {
    final collectionId = collectionOf(h.id, custom: isCustom);
    final chars = _extractCharacterIds(h.storyDetail);
    return ContentIdea(
      id: h.id,
      title: h.cover.isNotEmpty ? h.cover : h.opening,
      category: h.category,
      collectionId: collectionId,
      format: h.postFormat,
      problem: h.problem,
      lesson: h.lesson,
      opening: h.opening,
      storyDetail: h.storyDetail,
      characterIds: chars,
      caption: h.caption,
      isCustom: isCustom,
      status: _inferStatus(h),
      notes: '',
      sourceType: 'HookIdea',
    );
  }

  /// Converts a QuickIdea into a normalized ContentIdea.
  ContentIdea _quickIdeaToContentIdea(QuickIdea q) {
    final category = bucketToCategory(q.bucket);
    final collectionId = collectionOf(q.id);
    final chars = _extractCharacterIds(q.script);
    return ContentIdea(
      id: q.id,
      title: q.title,
      category: category,
      collectionId: collectionId,
      format: q.postType,
      problem: q.problem,
      lesson: q.lesson,
      opening: q.hook,
      storyDetail: q.script,
      characterIds: chars,
      caption: q.caption,
      isCustom: false,
      status: IdeaStatus.idea,
      notes: '',
      sourceType: 'QuickIdea',
    );
  }

  /// Converts an IdeaInboxItem into a normalized ContentIdea.
  ContentIdea _inboxToContentIdea(IdeaInboxItem i) {
    final bucket = BucketLibrary.byId(i.bucketId) ?? BucketLibrary.challenge;
    final category = bucket.name;
    final collectionId = collectionOf(i.id, custom: true);
    return ContentIdea(
      id: i.id,
      title: i.title,
      category: category,
      collectionId: collectionId,
      format: 'Reel',
      problem: i.rawIdea,
      lesson: '',
      opening: '',
      storyDetail: '',
      characterIds: const [],
      caption: '',
      isCustom: true,
      status: i.status,
      notes: i.notes,
      sourceType: 'IdeaInboxItem',
      sourceIdeaId: i.id,
    );
  }

  /// Infers production status from a HookIdea's fields.
  IdeaStatus _inferStatus(HookIdea h) {
    if (h.storyDetail.trim().isNotEmpty) return IdeaStatus.scripted;
    return IdeaStatus.idea;
  }

  /// Extracts character IDs from a story text by checking for known names.
  List<String> _extractCharacterIds(String text) {
    final lower = text.toLowerCase();
    final ids = <String>[];
    if (lower.contains('ria') || lower.contains('रिया')) ids.add('ria');
    if (lower.contains('rio') || lower.contains('रियो')) ids.add('rio');
    if (lower.contains('cuty') || lower.contains('क्यूटी')) ids.add('cuty');
    if (lower.contains('mumma') ||
        lower.contains('मम्मा') ||
        lower.contains('माँ') ||
        lower.contains('मम्मी'))
      ids.add('mumma');
    if (lower.contains('papa') ||
        lower.contains('पापा') ||
        lower.contains('पिता'))
      ids.add('papa');
    if (lower.contains('daadi') || lower.contains('दादी')) ids.add('daadi');
    if (lower.contains('teacher') || lower.contains('शिक्षक'))
      ids.add('teacher');
    return ids;
  }

  /// Maps a category label back to a bucket ID for storage.
  String _categoryToBucketId(String category) {
    // The category labels we use come from BucketLibrary names or HookIdea.category.
    // We try to find a bucket whose `name` matches.
    for (final b in BucketLibrary.all) {
      if (b.name.toLowerCase() == category.toLowerCase()) return b.id;
    }
    // Some HookIdea categories map to buckets:
    final legacyMap = {
      'Relatable': 'humor',
      'Struggle first': 'humor',
      'Surprising': 'humor',
      'Warm lesson': 'humor',
      'Page & milestone': 'community',
      'Series': 'community',
      'Navratri': 'community',
    };
    return legacyMap[category] ?? 'challenge';
  }

  // ── JSON persistence for user-added ContentIdea records ───────────────
  //
  // This storage is used to persist user-added ideas that go through the
  // ContentLibraryService.addIdea() path. It is separate from IdeaInboxStore
  // for backward compatibility — the inbox continues to read/write its own
  // format, while ContentLibraryService reads both.

  static const _storageFile = 'content_ideas.json';

  static Future<Directory> _getStoreDir() async {
    final dir = await getApplicationDocumentsDirectory();
    final storeDir = Directory('${dir.path}/content_library');
    await storeDir.create(recursive: true);
    return storeDir;
  }

  static Future<List<ContentIdea>> loadUserIdeas() async {
    try {
      final dir = await _getStoreDir();
      final file = File('${dir.path}/$_storageFile');
      if (!file.existsSync()) return [];
      final text = await file.readAsString();
      if (text.trim().isEmpty) return [];
      final raw = jsonDecode(text);
      if (raw is! List) return [];
      return raw
          .whereType<Map>()
          .map((json) {
            try {
              return ContentIdea.fromJson(Map<String, dynamic>.from(json));
            } catch (e) {
              debugPrint(
                'ContentLibraryService: skipped one unreadable idea — $e',
              );
              return null;
            }
          })
          .whereType<ContentIdea>()
          .toList();
    } catch (e) {
      debugPrint('ContentLibraryService: could not load user ideas — $e');
      return [];
    }
  }

  static Future<void> saveUserIdeas(List<ContentIdea> ideas) async {
    final dir = await _getStoreDir();
    await dir.create(recursive: true);
    final file = File('${dir.path}/$_storageFile');
    final json = jsonEncode(ideas.map((i) => i.toJson()).toList());
    await file.writeAsString(json);
  }
}
